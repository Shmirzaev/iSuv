export const translations: Record<Locale, Translation> = { en: english, ru: russian, uz: uzbek };
export const translate = (locale: Locale, key: TranslationKey): string => translations[locale][key];

export function initialLocale(value: string | null | undefined): Locale {
  return value && (locales as readonly string[]).includes(value) ? (value as Locale) : 'uz';
}
